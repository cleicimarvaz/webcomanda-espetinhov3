--      criar pelo Dashboard. O Storage do Supabase tem seu PRÓPRIO
--      sistema de RLS (storage.objects), separado do RLS das tabelas
--      normais desligado na seção 6.1 — por isso os dois precisam de
--      tratamento explícito, um não desliga o outro.
--
-- SEGURANÇA — LEIA ANTES DE COLOCAR EM PRODUÇÃO:
--   O client desta aplicação roda inteiramente no navegador com a chave
--   pública (anon key) do Supabase, sem backend próprio. Este script
