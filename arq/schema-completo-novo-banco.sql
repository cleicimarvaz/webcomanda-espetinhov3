-- 6.1. DESLIGA RLS (projetos novos do Supabase vêm com RLS ligado por
-- padrão e sem nenhuma política, o que bloqueia silenciosamente leitura
-- e escrita para o client desta aplicação, que usa só a chave pública).
-- Isso iguala ao comportamento do sistema em produção hoje, que não usa
-- RLS. Ver aviso de segurança no topo deste arquivo.
-- =====================================================================
do $$
declare
  t text;
begin
  for t in
    select unnest(array[
      'usuarios','auditoria','fornecedores','clientes','produtos',
      'produto_composicao','historico_precos','estoque_movimentacoes',
      'complementos','caixa','movimentacoes_caixa','comandas',
      'historico_vendas','despesas','contas_receber','metas_faturamento',
      'configuracoes_sistema','eventos','reservas_evento',
      'tipos_ingresso','ingressos'
    ])
  loop
    execute format('alter table public.%I disable row level security;', t);
  end loop;
end $$;

-- =====================================================================
-- 6.2. BUCKETS DE STORAGE ("produtos" e "eventos") + PERMISSÕES
-- =====================================================================
-- O código só usa getPublicUrl() (nunca link assinado), então os
-- buckets precisam ser públicos para a foto aparecer em qualquer tela.
-- storage.objects tem RLS sempre ligado no Supabase (não dá pra
-- desligar como nas tabelas normais) — por isso aqui é preciso criar
-- políticas explícitas de leitura/escrita para a chave pública (anon),
-- separado do bloco 6.1 acima.
--
-- Limites aplicados: 5MB por arquivo, apenas imagens (jpeg/png/webp/
-- heic/heif — heic/heif cobre fotos direto de iPhone). Ajuste
-- file_size_limit (em bytes) se quiser outro limite.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
    ('produtos', 'produtos', true, 5242880, array['image/jpeg','image/png','image/webp','image/heic','image/heif']),
    ('eventos', 'eventos', true, 5242880, array['image/jpeg','image/png','image/webp','image/heic','image/heif'])
on conflict (id) do nothing;

do $$
declare
  b text;
  acao text;
begin
  for b in select unnest(array['produtos', 'eventos'])
  loop
    foreach acao in array array['Leitura', 'Escrita', 'Atualizacao', 'Exclusao']
    loop
      execute format('drop policy if exists "%s publica bucket %s" on storage.objects;', acao, b);
    end loop;
    execute format('create policy "Leitura publica bucket %s" on storage.objects for select using (bucket_id = %L);', b, b);
    execute format('create policy "Escrita publica bucket %s" on storage.objects for insert with check (bucket_id = %L);', b, b);
    execute format('create policy "Atualizacao publica bucket %s" on storage.objects for update using (bucket_id = %L);', b, b);
    execute format('create policy "Exclusao publica bucket %s" on storage.objects for delete using (bucket_id = %L);', b, b);
  end loop;
end $$;

