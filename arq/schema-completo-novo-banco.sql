create table if not exists public.usuarios (
    id bigint generated by default as identity primary key,
    usuario text not null,
    senha text not null, -- ATENÇÃO: texto puro hoje, sem hash (ver aviso de segurança acima)
    nome text,
    role text default 'operador',
    nivel text default 'GARCOM', -- ADMIN, OPERADOR, GARCOM (usado para permissões na UI)
    ativo boolean not null default true,
    recebe_notificacoes boolean not null default false,
    modo_impressao text, -- preferência local de impressão do usuário (rawbt, pc, etc.)
    created_at timestamptz not null default now()
);
create unique index if not exists idx_usuarios_usuario on public.usuarios(usuario);

create table if not exists public.auditoria (
    id bigint generated by default as identity primary key,
    usuario text,
    tipo text, -- VENDA, ESTOQUE, FINANCEIRO, SEGURANÇA, SISTEMA...
