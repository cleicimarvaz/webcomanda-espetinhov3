-- 15. INTEGRIDADE EMPRESA x UNIDADE x PRODUTO
-- =====================================================================

create or replace function public.validar_contexto_estoque_v3()
returns trigger
language plpgsql
as $
declare
    v_empresa_produto uuid;
    v_empresa_unidade uuid;
begin
    select p.empresa_id
      into v_empresa_produto
      from public.produtos p
     where p.id = new.produto_id;

    select u.empresa_id
      into v_empresa_unidade
      from public.unidades u
     where u.id = new.unidade_id;

    if v_empresa_produto is null or v_empresa_unidade is null then
        raise exception 'Produto ou unidade inexistente.';
    end if;

    if v_empresa_produto <> v_empresa_unidade then
        raise exception 'Produto e unidade possuem contextos empresariais incompatíveis.';
    end if;

    -- estoque_produto_unidade não possui empresa_id: a empresa é derivada
    -- do produto e da unidade.
    if TG_TABLE_NAME = 'estoque_movimentacoes' then
        if new.empresa_id <> v_empresa_produto then
            raise exception 'Empresa, produto e unidade possuem contextos incompatíveis.';
        end if;
    end if;

    return new;
end;
$;

drop trigger if exists trg_validar_estoque_produto_unidade_v3
    on public.estoque_produto_unidade;

create trigger trg_validar_estoque_produto_unidade_v3
before insert or update on public.estoque_produto_unidade
for each row execute function public.validar_contexto_estoque_v3();

