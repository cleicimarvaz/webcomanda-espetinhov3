-- 9. CONFIGURAÇÕES
-- =====================================================================
-- A configuração é hierárquica por escopo.
--
-- Exemplos:
--   escopo = global   -> configuração geral da instalação
--   escopo = empresa  -> empresa_id preenchido
--   escopo = unidade  -> empresa_id + unidade_id
--   escopo = usuario  -> usuario_id
--
-- valor é JSONB para permitir boolean, número, texto ou objeto sem
-- criar uma tabela nova a cada preferência.

create table if not exists public.configuracoes_sistema (
    id uuid primary key default gen_random_uuid(),
    escopo text not null
        check (escopo in ('global', 'empresa', 'unidade', 'usuario')),
    empresa_id uuid references public.empresas(id) on delete cascade,
    unidade_id uuid references public.unidades(id) on delete cascade,
    usuario_id bigint references public.usuarios(id) on delete cascade,
    chave text not null,
    valor jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (
        (escopo = 'global' and empresa_id is null and unidade_id is null and usuario_id is null)
        or
        (escopo = 'empresa' and empresa_id is not null and unidade_id is null and usuario_id is null)
        or
        (escopo = 'unidade' and empresa_id is not null and unidade_id is not null and usuario_id is null)
        or
        (escopo = 'usuario' and empresa_id is null and unidade_id is null and usuario_id is not null)
    )
);

create unique index if not exists ux_config_global
    on public.configuracoes_sistema(chave)
    where escopo = 'global';

create unique index if not exists ux_config_empresa
    on public.configuracoes_sistema(empresa_id, chave)
    where escopo = 'empresa';

create unique index if not exists ux_config_unidade
    on public.configuracoes_sistema(unidade_id, chave)
    where escopo = 'unidade';

create unique index if not exists ux_config_usuario
    on public.configuracoes_sistema(usuario_id, chave)
    where escopo = 'usuario';

