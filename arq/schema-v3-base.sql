from public.estoque_produto_unidade e
join public.produtos p on p.id = e.produto_id;

create or replace view public.v_membros_organizacao_v3 as
select
    mo.id,
    mo.usuario_id,
    u.usuario,
    u.nome as usuario_nome,
    mo.empresa_id,
    e.nome as empresa_nome,
    mo.unidade_id,
    un.nome as unidade_nome,
    mo.papel_id,
    p.codigo as papel_codigo,
    p.nome as papel_nome,
    mo.ativo
from public.membros_organizacao mo
join public.usuarios u on u.id = mo.usuario_id
join public.empresas e on e.id = mo.empresa_id
left join public.unidades un on un.id = mo.unidade_id
join public.papeis p on p.id = mo.papel_id;

