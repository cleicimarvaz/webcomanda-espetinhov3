create or replace function public.validar_inventario_empresa_unidade_v3()
returns trigger
language plpgsql
as $$
begin
    if not exists (
        select 1
        from public.unidades u
        where u.id = new.unidade_id
          and u.empresa_id = new.empresa_id
    ) then
        raise exception 'A unidade do inventário não pertence à empresa.';
    end if;

    return new;
end;
$$;

